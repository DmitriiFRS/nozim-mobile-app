// Prepare only the static files needed by GitHub Pages. No dependencies or bundler.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'dist');
const marker = path.join(output, '.folio-generated');
if (fs.existsSync(output) && !fs.existsSync(marker)) {
  throw new Error('dist already exists and is not a generated Folio folder. Rename it before building.');
}
if (fs.existsSync(marker)) fs.rmSync(output, {recursive:true});
fs.mkdirSync(output, {recursive:true});
for (const file of ['index.html', 'css', 'js', 'assets', '.nojekyll']) {
  fs.cpSync(path.join(root, file), path.join(output, file), {recursive:true});
}
fs.writeFileSync(marker, 'Generated by scripts/build.js. Edit source files, then rebuild.\n');
console.log('Ready: dist/ — upload its contents to the root of your GitHub Pages repository.');
